const NBSP = "\u00a0";

/* устойчивые сочетания, которые нельзя рвать между строк */
const PHRASES = [/(love)\s+(story)/giu, /(қыз)\s+(ұзату)/giu, /(үйлену)\s+(той)/giu, /(сырға)\s+(салу)/giu];

/**
 * Неразрывные пробелы — только для текста, который выводится на экран. Не применять к данным,
 * которые режутся, сравниваются или уходят куда-то (лиды, JSON-LD, metadata, сравнение названий).
 */
export function nb(s: string): string {
  for (const re of PHRASES) s = s.replace(re, `$1${NBSP}$2`);
  return s
    .replace(/(?<=(?:^|[\s(«"„])\p{L}{1,2}) /gu, NBSP) // слова в 1-2 буквы: в, и, о, с, к, у, на, по, за, от, не…
    .replace(/(?<=\d) (?=[\p{L}₸%])/gu, NBSP) // «2 недели», «12 часов»
    .replace(/(?<=\d) (?=\d{3}(?!\d))/g, NBSP) // «12 000» — разряды числа
    .replace(/ (?=[—–·])/g, NBSP); // тире и «·» остаются в конце строки и не начинают новую
}
